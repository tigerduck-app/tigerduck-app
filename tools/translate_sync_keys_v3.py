def main():
    updated_count = 0
    for lang_code, sections in sorted(TRANSLATIONS.items()):
        filepath = os.path.join(SOURCE_DIR, f"{lang_code}.json")
        if not os.path.exists(filepath):
            print(f"  SKIP {lang_code} (file not found)")
            continue
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        changed = False
        for section_name, keys in sections.items():
            if section_name not in data:
                data[section_name] = {}
            for key, value in keys.items():
                en_section = "apple" if key in APPLE_KEYS else "shared"
                en_value = EN_VALUES.get(en_section, {}).get(key, "")
                old_en_value = OLD_EN_VALUES.get(en_section, {}).get(key)
                current = data[section_name].get(key)
                if current is None or current == en_value or (old_en_value and current == old_en_value):
                    data[section_name][key] = value
                    changed = True
        if changed:
            # Sort keys within each section
            for section_name in data:
                if isinstance(data[section_name], dict):
                    data[section_name] = dict(sorted(data[section_name].items()))
            with open(filepath, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
                f.write("\n")
            updated_count += 1
            print(f"  ✓ {lang_code}")
        else:
            print(f"  · {lang_code} (no changes needed)")
    print(f"\nUpdated {updated_count} language files.")


if __name__ == "__main__":
    main()
